#!/usr/bin/env bash
# CI ONLY. Execute the exact newest repository RPC and overlap trigger SQL
# in an isolated, disposable PostgreSQL 17 container. No Supabase connection.
set -Eeuo pipefail
umask 077
container="synthetic-recorder-$RANDOM-$RANDOM"
scratch="$(mktemp -d)"
cleanup() {
  docker rm -f "$container" >/dev/null 2>&1 || true
  rm -rf -- "$scratch"
}
trap cleanup EXIT

docker run -d --network none --name "$container" \
  -e POSTGRES_USER=postgres -e POSTGRES_PASSWORD=test-only-not-a-company-secret \
  -e POSTGRES_DB=synthetic_rpc \
  postgres:17 >/dev/null

ready=0
for attempt in $(seq 1 45); do
  ok="$(docker exec "$container" psql -X -A -t -U postgres \
    -d synthetic_rpc -c 'SELECT 1' 2>/dev/null || true)"
  if [[ "$ok" == 1 ]]; then
    ready=1
    break
  fi
  sleep 1
done
[[ "$ready" == 1 ]] || { docker logs "$container" >&2; exit 1; }

docker exec -i "$container" psql -X -v ON_ERROR_STOP=1 \
  -U postgres -d synthetic_rpc <<'SETUP_SQL'
-- The fixture below exists ONLY inside this disposable Docker database.
-- Do not execute it in Supabase or against any user database.
CREATE ROLE service_role NOLOGIN BYPASSRLS;
CREATE ROLE anon NOLOGIN;
CREATE ROLE authenticated NOLOGIN;

CREATE TABLE public.zamestnanci (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  meno text NOT NULL UNIQUE,
  aktivny boolean NOT NULL DEFAULT true
);
CREATE TABLE public.zoznam_zakaziek (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nazov text NOT NULL UNIQUE,
  stav text NOT NULL
);
CREATE TABLE public.objekty_stavby (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  zakazka_id bigint NOT NULL REFERENCES public.zoznam_zakaziek(id),
  nazov text NOT NULL,
  aktivny boolean NOT NULL DEFAULT true
);
CREATE TABLE public.dochadzka (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  meno text NOT NULL,
  zakazka text NOT NULL,
  datum date NOT NULL,
  prichod time NOT NULL,
  odchod time NOT NULL,
  objekt_id bigint REFERENCES public.objekty_stavby(id),
  sadzba_snapshot numeric(12,2)
);
INSERT INTO public.zamestnanci (meno, aktivny) VALUES
  ('CI Worker A',true),('CI Worker B',true),('CI Inactive Worker',false);
INSERT INTO public.zoznam_zakaziek (nazov, stav) VALUES
  ('CI Project A','Aktívna'),('CI Project B','Aktívna'),
  ('CI Inactive Project','Dokončená');
INSERT INTO public.objekty_stavby (zakazka_id,nazov,aktivny) VALUES
  (1,'CI Object A1',true),(2,'CI Object B1',true),(1,'CI Object Disabled',false);
ALTER TABLE public.zamestnanci ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.zoznam_zakaziek ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.objekty_stavby ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.dochadzka ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON ALL TABLES IN SCHEMA public FROM PUBLIC, anon, authenticated;
GRANT USAGE ON SCHEMA public TO service_role, anon, authenticated;
GRANT ALL ON ALL TABLES IN SCHEMA public TO service_role;
GRANT USAGE, SELECT ON ALL SEQUENCES IN SCHEMA public TO service_role;
SETUP_SQL

migration='supabase/migrations/20261001103500_project_objects.sql'
# Extract just the latest object-aware RPC and its privilege statements.
# Other migrations intentionally aren't replayed; no production schema is used.
awk '
  /^create or replace function public\.record_attendance_secure\(entries jsonb\)/ { copy=1; found=1 }
  copy { print }
  /^grant execute on function public\.record_attendance_secure\(jsonb\) to service_role;/ && copy { finished=1; exit }
  END { if (!found || !finished) exit 1 }
' "$migration" |
  docker exec -i "$container" psql -X -v ON_ERROR_STOP=1 \
    -U postgres -d synthetic_rpc

# Use the actual versioned trigger, not a hand-written approximation.
docker exec -i "$container" psql -X -v ON_ERROR_STOP=1 \
  -U postgres -d synthetic_rpc \
  < supabase/migrations/20260922105200_prevent_attendance_overlap.sql

docker exec -i "$container" psql -X -v ON_ERROR_STOP=1 \
  -U postgres -d synthetic_rpc \
  < tests/fixtures/recorder-rpc-integration.sql

# Two independent sessions try to record the same attendance concurrently.
# Lock + overlap detection must commit exactly one, reject the other.
payload='[{"meno":"CI Worker A","zakazka":"CI Project A","datum":"2026-10-23","prichod":"07:00","odchod":"18:00","objekt_id":1}]'
for i in 1 2; do
  (
    if docker exec "$container" psql -X -v ON_ERROR_STOP=1 \
      -U postgres -d synthetic_rpc \
      -c "SET ROLE service_role; SELECT public.record_attendance_secure('$payload'::jsonb);" \
      >"$scratch/out-$i.txt" 2>&1; then
      printf '0\n' > "$scratch/status-$i"
    else
      printf '1\n' > "$scratch/status-$i"
    fi
  ) &
done
wait
status_a="$(cat "$scratch/status-1")"
status_b="$(cat "$scratch/status-2")"
if [[ "$status_a$status_b" != 01 && "$status_a$status_b" != 10 ]]; then
  printf 'Concurrent RPCs must have one success and one conflict.\n' >&2
  cat "$scratch/out-1.txt" "$scratch/out-2.txt" >&2
  exit 1
fi
count="$(docker exec "$container" psql -X -A -t -U postgres \
  -d synthetic_rpc -c "SELECT count(*) FROM public.dochadzka
  WHERE meno='CI Worker A' AND datum='2026-10-23';")"
[[ "$count" == 1 ]] || {
  printf 'Concurrent RPC committed unexpected number of rows: %s\n' "$count" >&2
  exit 1
}

printf '%s\n' 'PASS: actual repository RPC, server-only grants, object validation, overlap trigger, atomicity and concurrent conflict on synthetic PostgreSQL 17.'
printf '%s\n' 'No production database connection, data, credentials or migrations were used.'
